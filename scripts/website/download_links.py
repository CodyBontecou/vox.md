"""App Store destinations. Attribution stays off until given a real Apple link."""

from html import escape, unescape
import json
from pathlib import Path
import re
from urllib.parse import parse_qs, urlencode, urlsplit

ROOT = Path(__file__).resolve().parents[2]
APP_ID = "6758967337"
QR_PATH = ROOT / "website/assets/download-qr.svg"
QR_METADATA = QR_PATH.with_suffix(".json")
ATTRIBUTE = re.compile(r'''\bhref\s*=\s*(["'])(.*?)\1''', re.I | re.S)
CAMPAIGN_ATTRIBUTE = re.compile(r'''\s+data-download-campaign\s*=\s*(["']).*?\1''', re.I | re.S)


def is_app_url(url):
    parsed = urlsplit(url)
    return (parsed.scheme == "https" and parsed.netloc == "apps.apple.com"
            and bool(re.search(rf"/id{APP_ID}/?$", parsed.path)))


def load_config(path=None):
    config = json.loads((path or ROOT / "website-content/downloads.json").read_text())
    if not is_app_url(config["app_store_url"]) or urlsplit(config["app_store_url"]).query:
        raise ValueError("app_store_url must be a direct HTTPS Vox.md App Store URL")
    campaigns = list(config["campaigns"].values()) + [config["qr_campaign"]]
    if any(not re.fullmatch(r"[a-z0-9_]{1,30}", token) for token in campaigns):
        raise ValueError("Campaign names must contain 1–30 lowercase letters, digits or underscores")
    if len(campaigns) != len(set(campaigns)):
        raise ValueError("Campaign names must be unique")
    for path in config["campaigns"]:
        if not path.startswith("/") or "?" in path or "#" in path or ".." in path:
            raise ValueError(f"Invalid campaign page path: {path}")
    verified = config.get("verified_campaign_link")
    if verified is not None:
        if not is_app_url(verified) or urlsplit(verified).fragment:
            raise ValueError("Use a campaign link generated by Apple for Vox.md")
        query = parse_qs(urlsplit(verified).query, keep_blank_values=True)
        if any(len(query.get(key, [])) != 1 for key in ("pt", "ct", "mt")):
            raise ValueError("Apple campaign link must include exactly one pt, ct and mt")
        if not re.fullmatch(r"[1-9][0-9]*", query["pt"][0]) or not query["ct"][0].strip() or query["mt"] != ["8"]:
            raise ValueError("Invalid Apple campaign parameters; copy the link from App Store Connect")
    return config


def destination(config, campaign):
    if not config.get("verified_campaign_link"):
        return config["app_store_url"]
    provider = parse_qs(urlsplit(config["verified_campaign_link"]).query)["pt"][0]
    return config["app_store_url"] + "?" + urlencode({"pt": provider, "ct": campaign, "mt": "8"})


def decorate_html(html, page_path, config=None):
    config = config or load_config()
    campaign = config["campaigns"].get(page_path)
    if campaign is None:
        raise ValueError(f"Add an App Store campaign mapping for {page_path}")

    def rewrite(match):
        tag = match[0]
        attribute = ATTRIBUTE.search(tag)
        if not attribute:
            return tag
        original = unescape(attribute[2])
        if not is_app_url(original) or "action" in parse_qs(urlsplit(original).query):
            return tag
        token = config["qr_campaign"] if 'data-download-kind="qr"' in tag else campaign
        url = escape(destination(config, token), quote=True)
        tag = tag[:attribute.start()] + f'href="{url}"' + tag[attribute.end():]
        tag = CAMPAIGN_ATTRIBUTE.sub("", tag)
        return tag[:-1] + f' data-download-campaign="{token}">'

    return re.sub(r"<a\b[^>]*>", rewrite, html, flags=re.I)


def page_path(path):
    relative = path.relative_to(ROOT / "website").as_posix()
    return "/" + (relative[:-len("index.html")] if relative.endswith("index.html") else relative)
